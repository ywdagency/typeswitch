#!/usr/bin/env python3
"""Export pinned Russian Hunspell suffix rules and flagged bases for offline lookup."""

from collections import Counter, defaultdict
from hashlib import sha256
from pathlib import Path
import re
from urllib.request import urlopen

REVISION = "836d7c2032167880e639a1fe522748733e528c2d"
SOURCE_URL = f"https://raw.githubusercontent.com/wooorm/dictionaries/{REVISION}/dictionaries/ru"
SOURCE_HASHES = {
    "index.aff": "38ce7d4af78e211e9bafe4bf7e3d6a2c420591136cb738ec6648f8fdf6524cd7",
    "index.dic": "f6047416a0204adbecf3a451b874ec8a97ee37e2cbc714466ef04d8dbcc0d6fc",
}
WORD = re.compile(r"[а-яё]{3,22}")
HEADER = (
    "# Generated by scripts/russian_inflections.py\n"
    f"# Source: wooorm/dictionaries at {REVISION}, dictionaries/ru/index.dic and index.aff.\n"
    "# Alexander I. Lebedev; license: LICENSES/hunspell-ru.txt. See docs/third-party-notices.md.\n"
)


def parse_suffix_rules(content):
    """Fail on unsupported Hunspell features instead of silently broadening matches."""
    declared = {}
    counts = Counter()
    rules = []
    for line in content.splitlines():
        fields = line.split()
        if not fields or fields[0].startswith("#"):
            continue
        if fields[0] == "SET" and fields == ["SET", "UTF-8"]:
            continue
        if fields[0] == "TRY" and len(fields) == 2:
            continue
        if fields[0] != "SFX" or len(fields) not in (4, 5):
            raise ValueError(f"Unsupported affix directive: {line}")
        flag = fields[1]
        if len(flag) != 1:
            raise ValueError("Only single-character affix flags are supported")
        if len(fields) == 4:
            if flag in declared or fields[2] not in ("Y", "N"):
                raise ValueError(f"Invalid suffix declaration: {line}")
            declared[flag] = int(fields[3])
            continue
        _, flag, strip, add, condition = fields
        if flag not in declared:
            raise ValueError("Suffix rule lacks a declaration")
        if any(value != "0" and not re.fullmatch(r"[а-яё]+", value) for value in (strip, add)):
            raise ValueError("Unsupported suffix or continuation flags")
        if not re.fullmatch(r"(?:[а-яё.]|\[\^?[а-яё]+\])+", condition):
            raise ValueError("Unsupported suffix condition")
        re.compile(f"(?:{condition})$")
        counts[flag] += 1
        rules.append((flag, strip, add, condition))
    if dict(counts) != declared:
        raise ValueError("Suffix rule counts differ from declarations")
    return sorted(set(rules))


def parse_bases(content, allowed_flags):
    bases = defaultdict(set)
    for line in content.splitlines()[1:]:
        word, separator, flags = line.partition("/")
        if not separator or WORD.fullmatch(word) is None:
            continue
        if set(flags) - allowed_flags:
            raise ValueError("Dictionary entry has unsupported flags")
        bases[word].update(flags)
    return [(word, "".join(sorted(flags))) for word, flags in sorted(bases.items())]


def generate_resources(resource_dir):
    sources = {}
    for filename, expected_hash in SOURCE_HASHES.items():
        with urlopen(f"{SOURCE_URL}/{filename}", timeout=30) as response:
            data = response.read()
        if sha256(data).hexdigest() != expected_hash:
            raise ValueError(f"Pinned source hash mismatch: {filename}")
        sources[filename] = data.decode("utf-8")

    rules = parse_suffix_rules(sources["index.aff"])
    bases = parse_bases(sources["index.dic"], {rule[0] for rule in rules})
    resource_dir.mkdir(parents=True, exist_ok=True)
    for filename, rows in [
        ("russian-inflection-bases.txt", bases),
        ("russian-inflection-rules.txt", rules),
    ]:
        (resource_dir / filename).write_text(
            HEADER + "\n".join("\t".join(row) for row in rows) + "\n", encoding="utf-8"
        )
        print(f"{filename}: {len(rows)} entries")


if __name__ == "__main__":
    generate_resources(Path(__file__).resolve().parents[1] / "Sources/TypeSwitchApp/Resources/FrequencyWords")
