#!/usr/bin/env python3
from pathlib import Path
from urllib.request import urlopen
import re
from russian_inflections import generate_resources

ROOT = Path(__file__).resolve().parents[1]
RESOURCE_DIR = ROOT / "Sources" / "TypeSwitchApp" / "Resources" / "FrequencyWords"

FREQUENCY_SOURCES = {
    "english.txt": {
        "url": "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt",
        "limit": 50000,
        "pattern": re.compile(r"^[a-z]+(?:'[a-z]+)?$"),
        "min_len": 3,
        "max_len": 18,
        "hunspell_url": "https://raw.githubusercontent.com/wooorm/dictionaries/main/dictionaries/en/index.dic",
    },
    "russian.txt": {
        "url": "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ru/ru_50k.txt",
        "limit": 50000,
        "pattern": re.compile(r"^[а-яё]+$"),
        "min_len": 3,
        "max_len": 22,
        "hunspell_url": "https://raw.githubusercontent.com/wooorm/dictionaries/main/dictionaries/ru/index.dic",
    },
    "ukrainian.txt": {
        "url": "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/uk/uk_50k.txt",
        "limit": 50000,
        "pattern": re.compile(r"^[а-щьюяєіїґ']+$"),
        "min_len": 2,
        "max_len": 22,
        "hunspell_url": "https://raw.githubusercontent.com/wooorm/dictionaries/main/dictionaries/uk/index.dic",
    },
}

HEADER = """# Generated by scripts/update-frequency-dictionaries.py
# Sources: hermitdave/FrequencyWords (OpenSubtitles 2018) and wooorm/dictionaries (Hunspell).
# Licenses and modification details: docs/third-party-notices.md.
"""

LANGUAGE_MARKER_RATIO = 8
LANGUAGE_MARKER_MIN_FREQUENCY = 100

KNOWN_GENERATED_NOISE = {
    "ukrainian.txt": {"щт", "туц", "філ", "філі", "уес", "рщт", "ьуп", "рьщ", "зоі"},
}


def fetch_words(source):
    with urlopen(source["url"], timeout=30) as response:
        raw_lines = response.read().decode("utf-8", errors="ignore").splitlines()

    words = []
    seen = set()
    for line in raw_lines:
        parts = line.strip().split()
        if not parts:
            continue

        word = parts[0].lower()
        if len(word) < source["min_len"] or len(word) > source["max_len"]:
            continue
        if source["pattern"].fullmatch(word) is None:
            continue
        if word in seen:
            continue

        seen.add(word)
        words.append(word)
        if len(words) >= source["limit"]:
            break

    return words


def fetch_frequency_counts(source):
    with urlopen(source["url"], timeout=30) as response:
        raw_lines = response.read().decode("utf-8", errors="ignore").splitlines()

    counts = {}
    for line in raw_lines:
        parts = line.strip().split()
        if len(parts) < 2 or source["pattern"].fullmatch(parts[0].lower()) is None:
            continue
        try:
            counts[parts[0].lower()] = int(parts[1])
        except ValueError:
            continue
    return counts


def fetch_hunspell_words(source):
    with urlopen(source["hunspell_url"], timeout=30) as response:
        raw_lines = response.read().decode("utf-8", errors="ignore").splitlines()

    words = []
    seen = set()
    for index, line in enumerate(raw_lines):
        value = line.strip()
        if not value or (index == 0 and value.isdigit()):
            continue

        word = value.split("/", 1)[0]
        if word != word.lower():
            continue
        if len(word) < source["min_len"] or len(word) > source["max_len"]:
            continue
        if source["pattern"].fullmatch(word) is None:
            continue
        if word in seen:
            continue

        seen.add(word)
        words.append(word)

    return words


def main():
    RESOURCE_DIR.mkdir(parents=True, exist_ok=True)
    for filename, source in FREQUENCY_SOURCES.items():
        frequency_words = fetch_words(source)
        hunspell_words = fetch_hunspell_words(source)
        noise = KNOWN_GENERATED_NOISE.get(filename, set())
        words = sorted(
            word for word in dict.fromkeys(frequency_words + hunspell_words)
            if word not in noise
        )
        output = RESOURCE_DIR / filename
        output.write_text(HEADER + "\n".join(words) + "\n", encoding="utf-8")
        print(
            f"{filename}: {len(words)} unique words "
            f"({len(frequency_words)} frequency + {len(hunspell_words)} Hunspell before dedupe)"
        )

    russian_counts = fetch_frequency_counts(FREQUENCY_SOURCES["russian.txt"])
    ukrainian_counts = fetch_frequency_counts(FREQUENCY_SOURCES["ukrainian.txt"])
    for filename, own_counts, other_counts in [
        ("russian-markers.txt", russian_counts, ukrainian_counts),
        ("ukrainian-markers.txt", ukrainian_counts, russian_counts),
    ]:
        markers = sorted(
            word for word, count in own_counts.items()
            if count >= LANGUAGE_MARKER_MIN_FREQUENCY
            and count >= max(other_counts.get(word, 0), 1) * LANGUAGE_MARKER_RATIO
        )
        (RESOURCE_DIR / filename).write_text(HEADER + "\n".join(markers) + "\n", encoding="utf-8")
        print(f"{filename}: {len(markers)} language-specific frequency markers")

    generate_resources(RESOURCE_DIR)


if __name__ == "__main__":
    main()
